package assignments.java;

public class Assignment20 {

	public static void main(String[] args) {
		/*
"-WAP using a for loop to print numbers from 1 to 100.
-WAP using a for loop to print numbers from -5 to 0.
-WAP using a for loop to print numbers from -5 to -2."
		 */
		
		for(int i=1; i<=100; i++)
		{
			System.out.println(i);
		}
		
		for(int j=-5; j<=0; j++)
		{
			System.out.println(j);
		}
		
		for(int k= -5; k<=-2;k++)
		{
			System.out.println(k);
		}
	}

}
