package assignments.java;

public class Assignment22 {

	public static void main(String[] args) {
		/*
		 WAP using nested loops to print 2 rows and 12 columns (outer loop and inner loop).
		 */
		for(int i=1; i<=2; i++)
		{
			for(int j=1; j<=12; j++)
			{
				System.out.print(i);
				System.out.println(" " +j);
			}
		}
	}

}
